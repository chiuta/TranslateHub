// Test: contorul „~N caractere / ~N tokeni” lângă Translate (caractere/4, fără prețuri, fără rețea).
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const require = createRequire(process.env.PW_ROOT || import.meta.url);
const {chromium} = require('playwright');
const FILE = 'file://' + path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'index.html');
let ok = 0, bad = 0;
const check = (n, c, x) => { if (c) { ok++; console.log('  ok   ' + n); } else { bad++; console.log('  FAIL ' + n + (x !== undefined ? '  → ' + JSON.stringify(x) : '')); } };
const b = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
const ctx = await b.newContext({viewport: {width: 1200, height: 1000}, locale: 'en-US'});
const reqs = [];
await ctx.route(/^https?:/, (r) => { reqs.push(r.request().url()); return r.abort(); });
const p = await ctx.newPage(); const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto(FILE); await p.waitForTimeout(500);
const est = () => p.textContent('#tok-est');
check('gol când nu există text', (await est()) === '');
await p.fill('#tr-source', 'a'.repeat(100)); await p.waitForTimeout(100);
check('100 caractere → ~25 tokeni (en)', (await est()) === '~100 chars / ~25 tokens', await est());
await p.fill('#tr-source', 'a'.repeat(1001)); await p.waitForTimeout(100);
check('1001 caractere → ~251 tokeni (rotunjit în sus, separator de mii)', /~1,001 chars \/ ~251 tokens/.test(await est()), await est());
check('lângă butonul Translate, fără prețuri', await p.evaluate(() => document.querySelector('.tr-action-row').contains(document.getElementById('tok-est')) && !/[$€]/.test(document.getElementById('tok-est').textContent)));
await p.evaluate(() => { document.documentElement.lang = 'ro'; });
await p.waitForTimeout(1300);
check('etichetă tradusă (ro)', /caractere \/ ~251 tokeni/.test(await est()), await est());
await p.fill('#tr-source', ''); await p.waitForTimeout(100);
check('revine la gol', (await est()) === '');
check('nicio cerere de rețea, fără pageerror', reqs.filter((u) => !/^file:/.test(u)).length === 0 && errs.length === 0, [reqs, errs]);
await b.close();
console.log('\n' + ok + ' ok, ' + bad + ' eșuate');
process.exit(bad ? 1 : 0);
